import { Router } from "express";
import { authenticate, authorize } from "../middleware/authenticate.js";
import { adminSummary, deleteCertificate, generateCertificate, logTrainerResultsViewed, reports, trainerActivity, trainerDashboard, listCertificates, listNotifications, sendNotification, listAuditLogs, listInvoices, createInvoice, updateInvoice, deleteInvoice, listCertificateTemplates, createCertificateTemplate, updateCertificateTemplate, deleteCertificateTemplate } from "../controllers/adminController.js";
const router = Router();
router.use(authenticate);
router.get("/trainer/dashboard", authorize("TRAINER"), trainerDashboard);
router.get("/trainer/activity", authorize("TRAINER"), trainerActivity);
router.post("/trainer/activity/results-viewed", authorize("TRAINER"), logTrainerResultsViewed);
router.get("/audit-logs", authorize("ADMIN", "SUPER_ADMIN"), listAuditLogs);
router.get("/notifications", authorize("ADMIN", "SUPER_ADMIN"), listNotifications);
router.post("/notifications", authorize("ADMIN", "SUPER_ADMIN"), sendNotification);
router.get("/billing/invoices", authorize("SUPER_ADMIN"), listInvoices);
router.post("/billing/invoices", authorize("SUPER_ADMIN"), createInvoice);
router.patch("/billing/invoices/:id", authorize("SUPER_ADMIN"), updateInvoice);
router.delete("/billing/invoices/:id", authorize("SUPER_ADMIN"), deleteInvoice);
router.get("/certificate-templates", authorize("ADMIN", "SUPER_ADMIN"), listCertificateTemplates);
router.post("/certificate-templates", authorize("ADMIN", "SUPER_ADMIN"), createCertificateTemplate);
router.patch("/certificate-templates/:id", authorize("ADMIN", "SUPER_ADMIN"), updateCertificateTemplate);
router.delete("/certificate-templates/:id", authorize("ADMIN", "SUPER_ADMIN"), deleteCertificateTemplate);
router.get("/certificates", authorize("ADMIN", "SUPER_ADMIN"), listCertificates);
router.post("/certificates", authorize("ADMIN", "SUPER_ADMIN"), generateCertificate);
router.delete("/certificates/:id", authorize("ADMIN", "SUPER_ADMIN"), deleteCertificate);
router.get("/reports", authorize("ADMIN", "SUPER_ADMIN"), reports);
router.get("/summary", authorize("ADMIN", "SUPER_ADMIN"), adminSummary);
router.post("/certificates/generate", authorize("ADMIN", "SUPER_ADMIN"), generateCertificate);
export default router;
